// ============================================================
// 유틸: 같은 색이 가로로 이어진 픽셀을 하나의 rect(run)로 합칩니다
// ============================================================
export type Run = { x: number; y: number; w: number; c: string };

export function toRuns(rows: Rows): Run[] {
  const runs: Run[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const c = row[x];
      if (c === '.') {
        x += 1;
        continue;
      }
      let w = 1;
      while (x + w < row.length && row[x + w] === c) w += 1;
      runs.push({ x, y, w, c });
      x += w;
    }
  });
  return runs;
}
